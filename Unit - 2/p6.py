# Unit 2 - Bitwise Operators

num1 = int(input("Enter first integer: "))
num2 = int(input("Enter second integer: "))

print("\n----- Bitwise Operations -----")

# Bitwise AND
print("AND (&)        :", num1 & num2)

# Bitwise OR
print("OR (|)         :", num1 | num2)

# Bitwise XOR
print("XOR (^)        :", num1 ^ num2)

# Bitwise NOT
print("NOT (~) num1   :", ~num1)
print("NOT (~) num2   :", ~num2)

# Left Shift
print("Left Shift (<<):", num1 << 1)

# Right Shift
print("Right Shift (>>):", num1 >> 1)