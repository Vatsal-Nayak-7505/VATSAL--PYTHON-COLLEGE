# Unit 2 - Membership Operators

# List
fruits = ["Apple", "Mango", "Banana", "Orange"]

print("----- List -----")
print("Mango in fruits:", "Mango" in fruits)
print("Grapes not in fruits:", "Grapes" not in fruits)


# Tuple
countries = ("India", "Japan", "Italy", "France")

print("\n----- Tuple -----")
print("India in countries:", "India" in countries)
print("USA not in countries:", "USA" not in countries)


# String
name = "Saumya Singh"

print("\n----- String -----")
print("'Saumya' in name:", "Saumya" in name)
print("'Python' not in name:", "Python" not in name)