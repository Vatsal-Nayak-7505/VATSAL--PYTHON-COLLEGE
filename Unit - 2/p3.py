# Unit 2 - Assignment Operators

num = 10

print("Initial value:", num)

# Assignment operator
num = 20
print("After = :", num)

# Addition assignment
num += 5
print("After += 5 :", num)

# Subtraction assignment
num -= 3
print("After -= 3 :", num)

# Multiplication assignment
num *= 2
print("After *= 2 :", num)

# Division assignment
num /= 4
print("After /= 4 :", num)

# Modulus assignment
num %= 3
print("After %= 3 :", num)

# Floor division assignment
num = 20
num //= 3
print("After //= 3 :", num)

# Exponentiation assignment
num = 2
num **= 3
print("After **= 3 :", num)